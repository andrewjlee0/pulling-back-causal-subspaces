"""The data-generating processes: the transition matrices of the six GHMM families, nonergodic mixtures, sampling, and
exact prediction.

Paper section: Appendix E (Data-generating processes) with Equations (8) to (13) and Table 1, and the conventions of
Appendix F with Equations (14) to (16).

Claim: In the paper's words, "We train on sequences generated by single Generalized Hidden Markov Models (GHMMs) or
processes that comprise nonergodic mixtures", and "By construction, each sampled sequence remains in one component."

Experiment: This module runs no experiment. The training script samples its sequences here, the context script samples
the evaluation contexts here, and the Figure 2 notebook computes the ground-truth next-token probabilities here.

Saved Outputs: None. This module writes no files.

How the code works: Each family function returns an array M of shape [V, S, S] with one matrix per symbol, where
M[z][i, j] is the weight of emitting symbol z while moving from hidden state i to hidden state j. This is the matrix
T^(z) of Appendix E. eta_of returns the right eigenvector with eigenvalue one of the sum of these matrices, which is
the all-ones vector for an HMM, and stationary returns the initial state. sample draws sequences by exact filtering,
which also works for GHMMs with negative entries, and sample_fast draws sequences of an HMM by rolling its hidden
state. plugin_nll returns the loss per token of the exact predictor, which the training script reports next to each
model's loss. joint_M builds a nonergodic mixture as one block-diagonal process whose initial state gives the
components equal weights. build turns one configuration of configs/process_configs.py into a dictionary with the name,
the matrices, the initial state, eta, and the number of symbols, and all_sweep_processes returns the 22 processes of
Table 1.
"""
import numpy as np

from configs.process_configs import SWEEP


# The six families of Appendix E. Each returns the matrices T^(z) stacked over the symbols z.
def mess3(alpha, x):
    b = (1 - alpha) / 2
    y = 1 - 2 * x
    ay, bx, by, ax = alpha * y, b * x, b * y, alpha * x
    return np.stack([
        np.array([[ay, bx, bx], [ax, by, bx], [ax, bx, by]]),
        np.array([[by, ax, bx], [bx, ay, bx], [bx, ax, by]]),
        np.array([[by, bx, ax], [bx, by, ax], [bx, bx, ay]]),
    ])


def arch(alpha):
    b = (1 - alpha) / 3
    return np.stack([
        np.array([[0.8*alpha, 0, 0, 0], [0, 0.2*alpha, 0, 0], [0, 0, 0.4*alpha, 0], [0, 0, 0, 0.6*alpha]]),
        np.array([[0, 0, 0, 0], [0, 0.4*alpha, 0, 0.4*b], [0, 0, 0.3*alpha, 0], [0, 0, 0, 0.16*alpha]]),
        np.array([[0.2*alpha, b, b, b], [b, 0.4*alpha, b, 0.6*b], [b, b, 0.3*alpha, b], [b, b, b, 0.24*alpha]]),
    ])


def wing(alpha, x):
    b = (1 - alpha) / 2
    return np.stack([
        np.array([[0, b, 0], [0, x*alpha, 0.5*b], [b, 0, 0]]),
        np.array([[alpha, 0, b], [b, (1-x)*alpha, 0.5*b], [0, b, alpha]]),
    ])


def strata(alpha, t0, t1):
    b = (1 - alpha) / 2
    return np.stack([
        np.array([[t0*alpha, 0, 0], [0, t1*alpha, 0], [0, 0, 0]]),
        np.array([[(1-t0)*alpha, b, b], [b, (1-t1)*alpha, b], [b, b, alpha]]),
    ])


def tom_quantum(alpha, beta):
    g2 = 1 / (4 * (alpha**2 + beta**2))
    c = 1 / 4
    m = (alpha**2 - beta**2) * g2
    o = 2 * alpha * beta * g2
    return np.stack([
        np.array([[c, 0, o], [0, m, 0], [o, 0, c]]),
        np.array([[c, 0, -o], [0, m, 0], [-o, 0, c]]),
        np.array([[c, o, 0], [o, c, 0], [0, 0, m]]),
        np.array([[c, -o, 0], [-o, c, 0], [0, 0, m]]),
    ])


def quantum_rrxor(phi, theta, eps=0.0):
    ct, st = np.cos(theta / 2), np.sin(theta / 2)
    cp, sp = np.cos(phi / 2), np.sin(phi / 2)
    K = [np.array([[ct * cp, -ct * sp], [-1j * st * sp, -1j * st * cp]]),
         np.array([[-1j * st * cp, 1j * st * sp], [ct * sp, ct * cp]])]
    sx = np.array([[0, 1], [1, 0]], dtype=complex)
    sy = np.array([[0, -1j], [1j, 0]])
    sz = np.array([[1, 0], [0, -1]], dtype=complex)
    B = [np.eye(2, dtype=complex) / 2, sx / 2, sy / 2, sz / 2]
    M = np.zeros((2, 4, 4))
    for x in range(2):
        G = np.zeros((4, 4))
        for m in range(4):
            for n in range(4):
                G[m, n] = 2 * np.real(np.trace(B[m] @ K[x] @ B[n] @ K[x].conj().T))
        M[x] = G
    if eps > 0:
        reset = np.zeros((4, 4)); reset[0, 0] = 1.0
        M = (1 - eps) * M + (eps / 2) * reset[None, :, :]
    return M


# Filtering, sampling, and the loss of the exact predictor.
def eta_of(M):
    T = M.sum(0)
    if np.all(M >= -1e-12) and np.allclose(T.sum(1), 1):
        return np.ones(M.shape[1])
    w, v = np.linalg.eig(T)
    eta = np.real(v[:, np.argmin(np.abs(w - 1))])
    if eta.sum() < 0:
        eta = -eta
    return eta


def stationary(M, eta=None):
    if eta is None:
        eta = eta_of(M)
    T = M.sum(0)
    w, v = np.linalg.eig(T.T)
    pi = np.real(v[:, np.argmin(np.abs(w - 1))])
    pi = pi / (pi @ eta)
    return pi


def sample(M, n, L, rng, eta=None, pi=None):
    eta = eta_of(M) if eta is None else eta
    pi = stationary(M, eta) if pi is None else pi
    V = M.shape[0]
    b = np.tile(pi, (n, 1))
    out = np.zeros((n, L), dtype=np.int64)
    for t in range(L):
        p = np.einsum("ni,zij,j->nz", b, M, eta)
        p = np.clip(p, 0, None)
        p = p / p.sum(1, keepdims=True)
        u = rng.random((n, 1))
        z = (u > p.cumsum(1)).sum(1)
        z = np.minimum(z, V - 1)
        out[:, t] = z
        bn = np.einsum("ni,nij->nj", b, M[z])
        b = bn / np.maximum((bn @ eta)[:, None], 1e-300)
    return out


def plugin_nll(M, seqs, eta=None, pi=None):
    eta = eta_of(M) if eta is None else eta
    pi = stationary(M, eta) if pi is None else pi
    n, L = seqs.shape
    b = np.tile(pi, (n, 1))
    nll = np.zeros(n)
    for t in range(L):
        p = np.einsum("ni,zij,j->nz", b, M, eta)
        p = np.clip(p, 1e-300, None)
        p = p / p.sum(1, keepdims=True)
        z = seqs[:, t]
        nll += -np.log(p[np.arange(n), z])
        bn = np.einsum("ni,nij->nj", b, M[z])
        b = bn / np.maximum((bn @ eta)[:, None], 1e-300)
    return nll.mean() / L


def sample_fast(M, n, L, rng, pi=None):
    assert np.all(M >= -1e-12), "GHMM: use sample()"
    V, S, _ = M.shape
    pi = stationary(M) if pi is None else pi
    FLAT = np.cumsum(M.transpose(1, 0, 2).reshape(S, V * S), axis=1)
    p0 = np.clip(pi, 0, None); p0 = p0 / p0.sum()
    s = rng.choice(S, size=n, p=p0)
    out = np.zeros((n, L), dtype=np.int64)
    u = rng.random((n, L))
    for t in range(L):
        k = (u[:, t, None] > FLAT[s]).sum(1)
        k = np.minimum(k, V * S - 1)
        out[:, t] = k // S
        s = k % S
    return out


# Nonergodic mixtures: the components occupy separate blocks of hidden states, so a sequence stays in the component it
# started in.
def joint_M(components, weights=None):
    V = components[0].shape[0]
    sizes = [c.shape[1] for c in components]
    S = sum(sizes)
    k = len(components)
    weights = np.full(k, 1 / k) if weights is None else np.asarray(weights)
    Mj = np.zeros((V, S, S))
    pij = np.zeros(S)
    o = 0
    for c, w, s in zip(components, weights, sizes):
        Mj[:, o:o+s, o:o+s] = c
        pij[o:o+s] = w * stationary(c, eta_of(c))
        o += s
    return Mj, pij


# The 22 processes of Table 1, built from configs/process_configs.py.
FAMILY_FN = {"mess3": mess3, "arch": arch, "wing": wing, "strata": strata,
             "tom_quantum": tom_quantum, "quantum_rrxor": quantum_rrxor}


def build(family, param):
    if family in ("nonergodic", "nonergodic2"):
        name, comp_kwargs = param
        comps = [mess3(**kw) for kw in comp_kwargs]
        Mj, pij = joint_M(comps)
        return dict(name=f"{family}_{name}", M=Mj, pi=pij, eta=eta_of(Mj),
                    V=Mj.shape[0], components=comps)
    name, kwargs = param
    M = FAMILY_FN[family](**kwargs)
    eta = eta_of(M)
    return dict(name=f"{family}_{name}", M=M, pi=stationary(M, eta), eta=eta,
                V=M.shape[0], components=None)


def all_sweep_processes():
    return [build(f, p) for f, plist in SWEEP.items() for p in plist]
